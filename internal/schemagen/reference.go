package schemagen

import (
	"fmt"
	"slices"
	"strings"

	"github.com/invopop/jsonschema"

	"github.com/solaria-sh/solaria/internal/api/v1alpha1"
)

// ReferenceDir holds the resource reference, one page per kind, relative to
// the module root. Every file in it is generated.
const ReferenceDir = "docs/resources"

// referencePages names each kind's page in ReferenceDir, in reading order.
var referencePages = []struct{ kind, file string }{
	{v1alpha1.KindAgent, "agent.md"},
	{v1alpha1.KindTarget, "target.md"},
	{v1alpha1.KindEnvironment, "environment.md"},
	{v1alpha1.KindMcpServer, "mcp-server.md"},
	{v1alpha1.KindVault, "vault.md"},
}

// Reference renders the resource reference: a page per kind, keyed by file
// name, each with a table of every field's path, type, whether it's
// required, and its description. It's generated from the same schema as the
// files in schemas/, so it can't drift from what validate checks.
func Reference() (map[string][]byte, error) {
	_, c, err := generate()
	if err != nil {
		return nil, err
	}
	pages := map[string][]byte{}
	for _, pg := range referencePages {
		kind := pg.kind
		var b strings.Builder
		b.WriteString("<!-- Generated by make schema from internal/api/" + v1alpha1.Version + ". Don't edit. -->\n\n")
		fmt.Fprintf(&b, "# %s\n\n", kind)
		if d := c.Definitions[kind+"Spec"]; d != nil && d.Description != "" {
			b.WriteString(d.Description + " ")
		}
		fmt.Fprintf(&b, "A YAML document with `apiVersion: %s` and `kind: %s`.", v1alpha1.APIVersion, kind)
		var others []string
		for _, o := range referencePages {
			if o.kind != kind {
				others = append(others, "["+o.kind+"]("+o.file+")")
			}
		}
		list := others[len(others)-1]
		if len(others) > 1 {
			list = strings.Join(others[:len(others)-1], ", ") + " and " + list
		}
		b.WriteString(" The other resources are " + list + ", and the [concepts](../concepts.md) explain how they fit together.\n\n")
		b.WriteString("## Fields\n\n")
		b.WriteString("The same rules are in the [JSON Schema](../../schemas/" + v1alpha1.Version + "/), which `solaria schema` prints for editors. ")
		b.WriteString("Paths use `.` for nested fields, `[]` for list items and `<name>` for map keys you choose.\n\n")
		b.WriteString("| Field | Type | Required | Description |\n|---|---|---|---|\n")
		r := &refWriter{defs: c.Definitions, b: &b}
		r.object("", c.Definitions[kind], nil)
		pages[pg.file] = []byte(b.String())
	}
	return pages, nil
}

type refWriter struct {
	defs jsonschema.Definitions
	b    *strings.Builder
}

// object writes a row for each of s's properties, then their own fields.
// seen holds the definitions on the current path, so recursive types end.
func (r *refWriter) object(prefix string, s *jsonschema.Schema, seen []string) {
	s, name := r.resolve(s)
	if name != "" {
		if slices.Contains(seen, name) {
			return
		}
		seen = append(seen, name)
	}
	if s.Properties == nil {
		return
	}
	for p := s.Properties.Oldest(); p != nil; p = p.Next() {
		path := prefix + p.Key
		prop := p.Value
		target, _ := r.resolve(prop)
		desc := prop.Description
		if desc == "" {
			desc = target.Description
		}
		required := ""
		if slices.Contains(s.Required, p.Key) {
			required = "yes"
		}
		fmt.Fprintf(r.b, "| `%s` | %s | %s | %s |\n", path, cell(r.typeOf(prop)), required, cell(desc+constraints(target)))

		switch {
		case target.Properties != nil:
			r.object(path+".", prop, seen)
		case target.Type == "array" && target.Items != nil:
			r.object(path+"[].", target.Items, seen)
		case target.Type == "object" && target.AdditionalProperties != nil:
			r.object(path+".<name>.", target.AdditionalProperties, seen)
		}
	}
}

// resolve follows a $ref, returning the definition and its name.
func (r *refWriter) resolve(s *jsonschema.Schema) (*jsonschema.Schema, string) {
	if name, ok := strings.CutPrefix(s.Ref, "#/$defs/"); ok {
		if d := r.defs[name]; d != nil {
			return d, name
		}
	}
	return s, ""
}

func (r *refWriter) typeOf(s *jsonschema.Schema) string {
	t, _ := r.resolve(s)
	switch {
	case t.Const != nil:
		return fmt.Sprintf("`%v`", t.Const)
	case len(t.Enum) > 0:
		var vs []string
		for _, v := range t.Enum {
			vs = append(vs, fmt.Sprintf("`%v`", v))
		}
		return strings.Join(vs, " or ")
	case t.Type == "array" && t.Items != nil:
		return "list of " + plural(r.typeOf(t.Items))
	case t.Type == "object" && t.Properties == nil && t.AdditionalProperties != nil:
		inner := r.typeOf(t.AdditionalProperties)
		if inner == "object" && t.AdditionalProperties.Properties == nil && t.AdditionalProperties.Ref == "" {
			return "map of objects"
		}
		return "map of " + plural(inner)
	case t.Type == "" && len(t.OneOf) > 0:
		// A field that takes one of several plain types, such as a path or
		// an inline object.
		var ts []string
		for _, o := range t.OneOf {
			if o.Type == "" || o.Ref != "" {
				return "any"
			}
			ts = append(ts, o.Type)
		}
		return strings.Join(ts, " or ")
	case t.Type == "":
		return "any"
	default:
		return t.Type
	}
}

// plural turns a plain type name into its plural; enums and other
// composite types stay as they are.
func plural(t string) string {
	switch t {
	case "string", "integer", "boolean", "number", "object":
		return t + "s"
	}
	return t
}

// constraints describes the checks a value's description doesn't already
// spell out.
func constraints(s *jsonschema.Schema) string {
	var c []string
	if s.Pattern != "" {
		c = append(c, "Matches `"+s.Pattern+"`.")
	}
	if s.Format != "" {
		c = append(c, "A "+strings.ToUpper(s.Format)+".")
	}
	if s.Type == "array" && s.Items != nil && s.Items.Pattern != "" {
		c = append(c, "Each matches `"+s.Items.Pattern+"`.")
	}
	if s.MinItems != nil && *s.MinItems > 0 {
		c = append(c, fmt.Sprintf("At least %d.", *s.MinItems))
	}
	if len(c) == 0 {
		return ""
	}
	return " " + strings.Join(c, " ")
}

// cell escapes text for a Markdown table cell.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
