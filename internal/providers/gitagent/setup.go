package gitagent

import (
	"fmt"
	"slices"
	"strings"

	"github.com/solaria-sh/solaria/internal/providers/container"
	"github.com/solaria-sh/solaria/internal/resolve"
)

const (
	// setupPath is the setup script in the build context, and setupBin
	// where the image has it.
	setupPath = "setup.sh"
	setupBin  = "/usr/local/bin/solaria-setup"
)

// setupScript is the image's entrypoint when the agent's Environment has
// setup steps (ADR 0022): it runs each step with sh -e in the workspace,
// then execs the command it's given, gitagent. A step gets PATH, HOME and
// its own variables, nothing else from the container. Docker passes the
// steps' secrets under their own names, and the script unsets those the
// run isn't given before it execs, so gitagent never sees them. It returns
// nil when there are no steps.
func setupScript(a *resolve.Agent) []byte {
	steps := a.Setup()
	if len(steps) == 0 {
		return nil
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("#!/bin/sh\n")
	w("# Generated by Solaria for %s in target %s: runs its Environment's\n", a.ID(), a.Target)
	w("# setup steps in the workspace, then gitagent (ADR 0022).\n")
	w("set -u\n")
	for _, st := range steps {
		w("\n# %s\n", st.Name)
		w(`env -i "PATH=$PATH" "HOME=$HOME"`)
		for _, kv := range st.Env {
			if kv.SecretRef != "" {
				w(` "%s=$%s"`, kv.Name, kv.SecretRef)
				continue
			}
			w(" %s", container.ShellQuote(kv.Name+"="+kv.Value))
		}
		w(" sh -e -c %s >&2 || {\n", container.ShellQuote(st.Run))
		w("  status=$?\n")
		w("  echo \"solaria: setup step %s exited with $status\" >&2\n", st.Name)
		w("  exit 2\n")
		w("}\n")
	}
	if unset := setupOnlySecrets(a); len(unset) > 0 {
		w("\nunset %s\n", strings.Join(unset, " "))
	}
	w("exec \"$@\"\n")
	return []byte(b.String())
}

// setupOnlySecrets lists the secrets the setup steps use and the run
// isn't given, sorted.
func setupOnlySecrets(a *resolve.Agent) []string {
	run := a.SecretRefs()
	var out []string
	for _, s := range a.SetupSecretRefs() {
		if !slices.Contains(run, s) {
			out = append(out, s)
		}
	}
	return out
}
