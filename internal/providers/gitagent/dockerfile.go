package gitagent

import (
	"fmt"
	"strings"

	"github.com/solaria-sh/solaria/internal/api/v1alpha1"
	"github.com/solaria-sh/solaria/internal/providers/container"
)

// Pinned inputs of the gitagent stage. Changing one changes every agent's
// image digest, so the next plan rebuilds them. The sandbox base's own pins
// are in the container package.
const (
	// GitagentCommit is the gitagent source the image builds, until v3 has
	// release binaries (see the gitagent spike). A Target can pick
	// another with providers.gitagent.commit.
	GitagentCommit = "f4a309cd600b877177c17ac789e83bd7355d0383"
	gitagentRepo   = "https://github.com/open-gitagent/gitagent.git"
	// rustImage matches the toolchain gitagent's rust-toolchain.toml pins.
	rustImage = "rust:1.99.0-bookworm"
)

type dockerfileData struct {
	LogicalID, Target string
	// Commit is the gitagent commit to build.
	Commit string
	// Base replaces the Solaria sandbox base when set.
	Base        string
	Packages    *v1alpha1.PackagesSpec
	Allow, Deny []string
}

// dockerfile generates the image's Dockerfile. Stages that don't depend on
// the agent come first, so Docker reuses them across agents and rebuilds.
func dockerfile(d dockerfileData) []byte {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# syntax=docker/dockerfile:1\n")
	w("# Generated by Solaria for %s in target %s.\n", d.LogicalID, d.Target)
	w("# Change the card or the target and run solaria apply instead of editing it.\n\n")

	w("# gitagent, built from a pinned commit on the build machine's own\n")
	w("# architecture and cross-compiled when the target differs.\n")
	w("FROM --platform=$BUILDPLATFORM %s AS gitagent\n", rustImage)
	w("ARG TARGETARCH\n")
	w("ARG GITAGENT_COMMIT=%s\n", d.Commit)
	w("RUN git init /src && cd /src \\\n")
	w(" && git remote add origin %s \\\n", gitagentRepo)
	w(" && git fetch --depth 1 origin \"$GITAGENT_COMMIT\" && git checkout FETCH_HEAD\n")
	w("WORKDIR /src\n")
	w("RUN --mount=type=cache,target=/usr/local/cargo/registry set -eu; \\\n")
	w("    case \"$TARGETARCH\" in amd64) arch=x86_64 ;; arm64) arch=aarch64 ;; *) echo \"unsupported architecture $TARGETARCH\" >&2; exit 1 ;; esac; \\\n")
	w("    target=\"$arch-unknown-linux-gnu\"; \\\n")
	w("    if [ \"$(uname -m)\" != \"$arch\" ]; then \\\n")
	w("      apt-get update && apt-get install -y --no-install-recommends \"gcc-$(echo \"$arch\" | tr _ -)-linux-gnu\" \"libc6-dev-$TARGETARCH-cross\"; \\\n")
	w("      export \"CARGO_TARGET_$(echo \"$target\" | tr a-z- A-Z_)_LINKER=$arch-linux-gnu-gcc\" \"CC_$(echo \"$target\" | tr - _)=$arch-linux-gnu-gcc\"; \\\n")
	w("    fi; \\\n")
	w("    rustup target add \"$target\"; \\\n")
	w("    cargo build --release --locked --target \"$target\" --bin gitagent; \\\n")
	w("    cp \"target/$target/release/gitagent\" /usr/local/bin/gitagent\n\n")

	container.WriteSandboxStages(&b, d.Base, d.Packages)

	w("# The agent: gitagent and its config layer. Only these layers change when\n")
	w("# the card does.\n")
	w("FROM sandbox\n")
	w("COPY --from=gitagent /usr/local/bin/gitagent /usr/local/bin/gitagent\n")
	w("COPY home/ /root/\n")
	w("ENV HOME=/root\n")
	w("WORKDIR /workspace\n")
	entry := []string{"gitagent"}
	if len(d.Allow) > 0 {
		entry = append(entry, "--allowed-tools", strings.Join(d.Allow, ","))
	}
	if len(d.Deny) > 0 {
		entry = append(entry, "--disallowed-tools", strings.Join(d.Deny, ","))
	}
	w("ENTRYPOINT %s\n", container.JSONArray(entry))
	return []byte(b.String())
}
